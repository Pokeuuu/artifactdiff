"""Regenerate examples/<format>/{old,new}.<ext> and expected.json.

All examples are synthetic and generated from code in tests/samples.py, so they are freely
distributable (Apache-2.0, like the rest of the repository).

Usage: python scripts/generate_examples.py [--check]
  --check  fail if regenerated expected.json files differ from the committed ones
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))

import samples  # noqa: E402

from artifactdiff.engine import Engine  # noqa: E402
from artifactdiff_cli.demo import expected_summary  # noqa: E402

EXAMPLES = ROOT / "examples"
GENERATORS = {
    "json": samples.json_pair,
    "csv": samples.csv_pair,
    "parquet": samples.parquet_pair,
    "sqlite": samples.sqlite_pair,
    "image": samples.image_pair,
    "audio": samples.audio_pair,
    "pdf": samples.pdf_pair,
    "gltf": samples.gltf_pair,
    "safetensors": samples.safetensors_pair,
}
DESCRIPTIONS = {
    "json": "Model configuration: renamed model, changed layer, inserted layer, type change, removed tag.",
    "csv": "User table: removed/added/modified rows (auto-detected `id` key), new column, missing value.",
    "parquet": "Orders: type change, new nullable column, nullability change, compression change, rows.",
    "sqlite": "App database: tables, columns, index, trigger and row changes (keyed and un-keyed tables).",
    "image": "A new red rectangle (one changed region) and an added PNG text chunk.",
    "audio": "A 440 Hz tone becomes a quieter 660 Hz tone with 0.6 s of trailing silence.",
    "pdf": "Changed revenue figure, added appendix page, changed title metadata.",
    "gltf": "Deformed cube with unchanged vertex counts, moved marker, added object, material colour.",
    "safetensors": "Fine-tuned weights, a renamed tensor, a reshaped head, an added layer, metadata.",
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    engine = Engine()
    failures = 0
    for name, gen in GENERATORS.items():
        out = EXAMPLES / name
        with tempfile.TemporaryDirectory() as tmp:
            a, b = gen(Path(tmp))
            result = engine.compare(a, b)
            summary = expected_summary(result)
            if args.check:
                expected = json.loads((out / "expected.json").read_text(encoding="utf-8"))
                if expected != summary:
                    print(f"MISMATCH {name}")
                    failures += 1
                continue
            out.mkdir(parents=True, exist_ok=True)
            for old in out.glob("old.*"):
                old.unlink()
            for new in out.glob("new.*"):
                new.unlink()
            shutil.copy(a, out / a.name)
            shutil.copy(b, out / b.name)
        (out / "expected.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
        (out / "README.md").write_text(
            f"# {name} example\n\n{DESCRIPTIONS[name]}\n\n```bash\nartifactdiff diff examples/{name}/{a.name} "
            f"examples/{name}/{b.name}\n```\n\n`expected.json` lists the expected status and the (kind, category, "
            f"path) of every change; `artifactdiff demo --check` verifies it. Generated by "
            f"`scripts/generate_examples.py` (synthetic data).\n",
            encoding="utf-8",
        )
        print(f"{name}: {result.status.value}, {result.statistics.total_changes} change(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
