"""GitHub-flavoured Markdown reports (used for pull-request comments).

All file names and values may come from untrusted pull requests, so they are escaped: HTML is
neutralised, table pipes are escaped and ``@`` is broken up to avoid pinging users.
"""

from __future__ import annotations

from artifactdiff.models import ComparisonResult, ComparisonStatus, FileEntryStatus, Report, ReportEntry
from artifactdiff.reporting import format_value

STATUS_ICON = {
    ComparisonStatus.IDENTICAL: "⚪",
    ComparisonStatus.EQUIVALENT: "⚪",
    ComparisonStatus.DIFFERENT: "🟡",
    ComparisonStatus.ERROR: "🔴",
    ComparisonStatus.UNSUPPORTED: "⚫",
}
SEVERITY_ICON = {"info": "ℹ️", "low": "🟢", "medium": "🟠", "high": "🔴"}
MARKER = "<!-- artifactdiff-report -->"


def esc(text: object) -> str:
    s = str(text)
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("|", "\\|").replace("\n", " ").replace("\r", " ")
    s = s.replace("@", "@\u200b").replace("`", "ˋ")
    return s


def code(text: object) -> str:
    return f"<code>{esc(text)}</code>"


def _result_section(result: ComparisonResult, max_changes: int) -> list[str]:
    lines: list[str] = []
    plugin = f"{result.plugin.name} {result.plugin.version}" if result.plugin else "none"
    lines.append(f"**{esc(result.summary)}** · plugin `{esc(plugin)}` · status `{result.status.value}`")
    lines.append("")
    if result.error:
        lines += [f"> ❗ {esc(result.error)}", ""]
    o, n = result.old, result.new
    lines.append(f"Size: {o.size_bytes:,} → {n.size_bytes:,} bytes · sha256 `{o.sha256[:12]}` → `{n.sha256[:12]}`")
    lines.append("")
    if result.changes:
        lines.append("| | Kind | Path | Change | Old | New |")
        lines.append("|---|---|---|---|---|---|")
        for c in result.changes[:max_changes]:
            lines.append(
                f"| {SEVERITY_ICON.get(c.severity.value, '')} | {c.kind.value} | {code(c.path)} | "
                f"{esc(c.description)} | {esc(format_value(c.old_value, 60))} | "
                f"{esc(format_value(c.new_value, 60))} |"
            )
        hidden = result.statistics.total_changes - min(len(result.changes), max_changes)
        if hidden > 0:
            lines.append("")
            lines.append(f"_…and {hidden:,} more change(s). See the HTML/JSON report artifact._")
        lines.append("")
    if result.statistics.metrics:
        lines.append("<details><summary>Metrics</summary>")
        lines.append("")
        for k, v in result.statistics.metrics.items():
            lines.append(f"- `{esc(k)}`: {esc(format_value(v, 100))}")
        lines += ["", "</details>", ""]
    if result.warnings:
        lines.append("<details><summary>⚠️ Warnings</summary>")
        lines.append("")
        lines += [f"- **{esc(w.code)}**: {esc(w.message)}" for w in result.warnings]
        lines += ["", "</details>", ""]
    if result.limitations:
        lines.append("<details><summary>Limitations of this comparison</summary>")
        lines.append("")
        lines += [f"- {esc(t)}" for t in result.limitations]
        lines += ["", "</details>", ""]
    return lines


def _entry_heading(e: ReportEntry) -> str:
    icon = {
        FileEntryStatus.ADDED: "🆕",
        FileEntryStatus.REMOVED: "🗑️",
        FileEntryStatus.RENAMED: "↪️",
        FileEntryStatus.UNCHANGED: "⚪",
    }.get(e.file_status, STATUS_ICON.get(e.result.status, "") if e.result else "🔴")
    name = code(e.path)
    if e.old_path and e.old_path != e.path:
        name = f"{code(e.old_path)} → {name}"
    return f"#### {icon} {name}"


def render_markdown(report: Report, *, max_changes: int = 25, max_chars: int | None = None) -> str:
    s = report.summary
    lines = [MARKER, f"## 🔍 {esc(report.title)}", ""]
    lines.append(
        f"**{s.files}** file(s) · **{s.with_changes}** with changes · **{s.total_changes:,}** change(s)"
        + (f" · max severity **{s.max_severity.value}**" if s.max_severity else "")
        + (f" · **{s.errors}** error(s)" if s.errors else "")
        + (f" · {s.added_files} added / {s.removed_files} removed" if s.added_files or s.removed_files else "")
    )
    lines.append("")
    if not report.entries:
        lines += ["No supported artifacts changed.", ""]
    for e in report.entries:
        lines.append(_entry_heading(e))
        lines.append("")
        if e.note:
            lines += [f"_{esc(e.note)}_", ""]
        if e.result is not None:
            lines += _result_section(e.result, max_changes)
        elif e.file_status == FileEntryStatus.ADDED:
            lines += ["File added.", ""]
        elif e.file_status == FileEntryStatus.REMOVED:
            lines += ["File removed.", ""]
    lines.append(
        f"<sub>Generated by ArtifactDiff {esc(report.artifactdiff_version)} · "
        f"{report.generated_at:%Y-%m-%d %H:%M UTC} · comparisons ran locally on the CI runner</sub>"
    )
    text = "\n".join(lines) + "\n"
    if max_chars is not None and len(text) > max_chars:
        note = "\n\n_Report truncated to fit the comment size limit. See the uploaded report artifact._\n"
        text = text[: max_chars - len(note)].rsplit("\n", 1)[0] + note
    return text
